local ls = require('luasnip')
local s = ls.snippet
local t = ls.text_node
local i = ls.insert_node

local function array_callback(method, body)
  return {
    i(1, 'items'),
    t('.' .. method .. '(('),
    i(2, 'item'),
    t(') => '),
    i(3, body),
    t(')'),
  }
end

return {
  s({ trig = 'dc', name = 'Declare const' }, {
    t('const '),
    i(1, 'name'),
    t(' = '),
    i(2, 'value'),
    t(';'),
  }),
  s({ trig = 'dv', name = 'Declare variable with let' }, {
    t('let '),
    i(1, 'name'),
    t(' = '),
    i(2, 'value'),
    t(';'),
  }),
  s({ trig = 'do', name = 'Destructure object' }, {
    t('const { '),
    i(1, 'key'),
    t(' } = '),
    i(2, 'source'),
    t(';'),
  }),
  s({ trig = 'da', name = 'Destructure array' }, {
    t('const ['),
    i(1, 'first'),
    t(', '),
    i(2, 'second'),
    t('] = '),
    i(3, 'items'),
    t(';'),
  }),
  s({ trig = 'dfn', name = 'Declare function' }, {
    t('function '),
    i(1, 'name'),
    t('('),
    i(2, 'args'),
    t({ ') {', '\t' }),
    i(0),
    t({ '', '}' }),
  }),
  s({ trig = 'dafn', name = 'Declare async function' }, {
    t('async function '),
    i(1, 'name'),
    t('('),
    i(2, 'args'),
    t({ ') {', '\t' }),
    i(0),
    t({ '', '}' }),
  }),
  s({ trig = 'arrow', name = 'Arrow function expression' }, {
    t('('),
    i(1, 'args'),
    t(') => '),
    i(2, 'expression'),
  }),
  s({ trig = 'tern', name = 'Ternary expression' }, {
    i(1, 'condition'),
    t(' ? '),
    i(2, 'whenTrue'),
    t(' : '),
    i(3, 'whenFalse'),
  }),
  s({ trig = 'map', name = 'Map array items' }, array_callback('map', 'expression')),
  s({ trig = 'filter', name = 'Filter array items' }, array_callback('filter', 'condition')),
  s({ trig = 'find', name = 'Find an array item' }, array_callback('find', 'condition')),
  s({ trig = 'some', name = 'Test whether any array item matches' }, array_callback('some', 'condition')),
  s({ trig = 'every', name = 'Test whether every array item matches' }, array_callback('every', 'condition')),
  s({ trig = 'reduce', name = 'Reduce array items' }, {
    i(1, 'items'),
    t('.reduce(('),
    i(2, 'acc'),
    t(', '),
    i(3, 'item'),
    t(') => '),
    i(4, 'expression'),
    t(', '),
    i(5, 'initial'),
    t(')'),
  }),
  s({ trig = 'cl', name = 'console.log' }, {
    t('console.log('),
    i(1, 'value'),
    t(');'),
    i(0),
  }),
  s({ trig = 'logv', name = 'Log a variable with its name' }, {
    t('console.log({ '),
    i(1, 'value'),
    t(' });'),
  }),
  s({ trig = 'logt', name = 'Log data as a table' }, {
    t('console.table('),
    i(1, 'rows'),
    t(');'),
  }),
  s({ trig = 'guard', name = 'Early return guard' }, {
    t('if ('),
    i(1, '!value'),
    t(') return;'),
  }),
  s({ trig = '$on', name = 'jQuery delegated event handler' }, {
    t('$('),
    i(1, '"#container"'),
    t(').on('),
    i(2, '"click"'),
    t(', '),
    i(3, '".target"'),
    t(', function('),
    i(4, 'event'),
    t({ ') {', '\t' }),
    i(5),
    t({ '', '});' }),
  }),
  s({ trig = '$get', name = 'jQuery GET request' }, {
    t('$.get('),
    i(1, '"/controllers/example-controller/"'),
    t(', '),
    i(2, '{}'),
    t(')'),
  }),
  s({ trig = '$post', name = 'jQuery POST request' }, {
    t('$.post('),
    i(1, '"/controllers/example-controller/"'),
    t(', '),
    i(2, '{}'),
    t(')'),
  }),
  s({ trig = 'jsform', name = 'JavaScript form submit handler' }, {
    i(1, 'formElement'),
    t({
      '.addEventListener("submit", (event) => {',
      '\tevent.preventDefault();',
      '',
      '\tconst form = event.currentTarget;',
      '\tif (!form.reportValidity()) return;',
      '',
      '\tconst data = new FormData(form, event.submitter);',
      '\t',
    }),
    i(0),
    t({ '', '});' }),
  }),
  s({ trig = 'jsparallel', name = 'Await independent promises in parallel' }, {
    t('const ['),
    i(1, 'firstResult'),
    t(', '),
    i(2, 'secondResult'),
    t({ '] = await Promise.all([', '\t' }),
    i(3, 'firstTask()'),
    t({ ',', '\t' }),
    i(4, 'secondTask()'),
    t({ ',', ']);' }),
  }),
}
